"""A symbol map of the repo, so agents grep for where things are instead of reading whole packages.

Agents lose what they read whenever their context is summarized, then read the same files again.
One line per top-level declaration (file:line plus the declaration) answers most "where is X"
questions in a single grep.
"""

import re
from pathlib import Path

from . import git

DECL = {
    ".go": re.compile(r"^(func|type)\s"),
    ".rs": re.compile(r"^\s*(pub(\([^)]*\))?\s+)?(async\s+)?(fn|struct|enum|trait|impl|mod)\b"),
    ".py": re.compile(r"^(async\s+def|def|class)\s"),
    ".ts": re.compile(r"^export\s|^(async\s+)?function\s|^(abstract\s+)?class\s|^interface\s|^type\s"),
    ".sql": re.compile(r"^--\s*name:|^CREATE\s+(TABLE|INDEX|TYPE|VIEW|FUNCTION)", re.I),
}
DECL[".tsx"] = DECL[".js"] = DECL[".jsx"] = DECL[".mjs"] = DECL[".ts"]
SKIP_DIRS = ("vendor/", "node_modules/", "dist/", "build/", "target/", ".foundry/", "testdata/")
LIMIT = 400_000  # bytes; beyond this the map stops listing (it says so)


def build(repo: Path) -> str:
    out, size = [], 0
    for path in git.git(repo, "ls-files").splitlines():
        rx = DECL.get(Path(path).suffix)
        if not rx or any(f"/{d}" in f"/{path}" for d in SKIP_DIRS) or path.endswith(".pb.go"):
            continue
        try:
            lines = (repo / path).read_text(errors="replace").splitlines()
        except OSError:
            continue
        # One self-contained line per declaration, so any grep hit names its file and line.
        block = "".join(f"{path}:{i}: {ln.strip()[:140].rstrip('{ ')}\n"
                        for i, ln in enumerate(lines, 1) if rx.search(ln))
        if size + len(block) > LIMIT:
            out.append("... (map truncated: grep the code for the rest)\n")
            break
        out.append(block)
        size += len(block)
    head = ("# Repo map (generated by foundry before this attempt)\n"
            "Every top-level declaration as `file:line: declaration`. It is large: grep it, never read it whole.\n"
            "  grep -i 'tenant' .foundry/map.md\n"
            "then read just the lines you need of the file it points to (offset/limit).\n\n")
    return head + "".join(out)
